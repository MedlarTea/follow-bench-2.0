#!/usr/bin/env python3
"""Create the files a new FollowBench scene needs.

    python tools/map_annotator/create_scenario_scaffold.py --scenario-name warehouse

creates

    assets/scenes/<name>/                  put gridmap_roi.npz + gridmap_roi_flow_points.json here
    configs/scenes/<name>/episode.sh       launch preset (reuses the plaza runner by default)
    configs/scenes/<name>/batch/smoke_test.sh
    docs/scenes/<name>.md

after which `bash scripts/run_episode.sh --scene <name>` and
`bash scripts/run_batch_eval.sh --scene <name> --config smoke_test` work.
"""
from __future__ import annotations

import argparse
from pathlib import Path

from followbench.paths import REPO_ROOT

EPISODE_TEMPLATE = """# shellcheck shell=bash
# {name} scene preset (generated by tools/map_annotator/create_scenario_scaffold.py).
# See configs/scenes/passage/episode.sh for the preset contract.

SCENE_HUMANOID_SUPPORTED=0
# Reuse an existing runner; the evaluation logs are still labelled '{name}'.
SCENE_RUNNER_MODULE="{runner}"

scene_episode_args() {{
  PLANNER="${{PLANNER:-gt_planner}}"
  FOLLOW_POSITION="${{FOLLOW_POSITION:-back}}"
  DESIRED_DISTANCE="${{DESIRED_DISTANCE:-1.5}}"
  NUM_WALKERS="${{NUM_WALKERS:-{num_walkers}}}"
  require_asset gridmap_roi.npz
  require_asset gridmap_roi_flow_points.json
  EPISODE_ARGS=(
    --load-map
    --map-name {map_name}
    --grid-npz "$FB_ASSETS_DIR/gridmap_roi.npz"
    --flow-points-json "$FB_ASSETS_DIR/gridmap_roi_flow_points.json"
    --robot-spawn-mode near_target
    --num-walkers "$NUM_WALKERS"
    --target-track-id N01
    --visibility-threshold 400
    --robot-rescue-lift-z 0.25
    --sensor-image-w 800
    --sensor-image-h 600
    --sensor-fov-deg 90
    --duration-sec {duration_sec}
    --draw-debug
    --draw-laser
    --planner "$PLANNER"
    --follow-position "$FOLLOW_POSITION"
    --desired-distance "$DESIRED_DISTANCE"
    --enable-evaluation
    --eval-scenario-type {name}
    --output-dir "$FB_RUNS_DIR"
  )
}}

scene_walkers_for() {{ echo "${{NUM_WALKERS_TOTAL}}"; }}
scene_batch_defaults() {{ NUM_WALKERS_TOTAL="${{NUM_WALKERS_TOTAL:-{num_walkers}}}"; }}
scene_batch_slot_args() {{
  export NUM_WALKERS="$NUM_WALKERS_TOTAL"
  SLOT_ARGS=(--num-walkers "$NUM_WALKERS_TOTAL" --no-ui)
}}
"""

SMOKE_TEMPLATE = """PLANNERS_WITH_PERCEPTION=""
PLANNERS_BACK_ONLY="gt_planner"
DIFFICULTIES="easy"
FOLLOW_POSITIONS_BACK_ONLY="back"
DESIRED_DISTANCE="1.5"
REPEATS="1"
RESUME="0"
"""

DOC_TEMPLATE = """# {name} scene

Generated by `tools/map_annotator/create_scenario_scaffold.py`. The episode is
run by `{runner}` with the preset in `configs/scenes/{name}/episode.sh`.

## Assets

Put these files in `assets/scenes/{name}/`:

- `gridmap_roi.npz`
- `gridmap_roi_flow_points.json`

1. Record the ROI in CARLA (the interactive `carla_walk_roi_annotator.py` is not part
   of this release; see `tools/map_annotator/README.md`).
2. Convert it with `tools/map_annotator/convert_roi_to_minimal_assets.py --output-dir assets/scenes/{name}`.

## Run

```bash
bash scripts/run_episode.sh --scene {name}
bash scripts/run_batch_eval.sh --scene {name} --config smoke_test
```

Default map: `{map_name}`. Crowd size, speeds and duration are set in the preset.
"""


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description="Create the scaffold for a new FollowBench scene.")
    p.add_argument("--scenario-name", required=True, help="new scene name, e.g. warehouse")
    p.add_argument("--runner", default="followbench.scenes.plaza.run_episode",
                   help="episode runner module to reuse")
    p.add_argument("--map-name", default="Town10HD_Opt")
    p.add_argument("--num-walkers", type=int, default=28)
    p.add_argument("--duration-sec", type=float, default=300.0)
    p.add_argument("--overwrite", action="store_true")
    return p.parse_args()


def write_text(path: Path, content: str, overwrite: bool) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and not overwrite:
        print(f"keep existing {path.relative_to(REPO_ROOT)}")
        return
    path.write_text(content, encoding="utf-8")
    print(f"wrote {path.relative_to(REPO_ROOT)}")


def main() -> None:
    args = parse_args()
    name = args.scenario_name.strip()
    if not name or not name.replace("_", "").isalnum():
        raise SystemExit("scenario-name must be a single identifier (letters, digits, '_')")
    fmt = dict(name=name, runner=args.runner, map_name=args.map_name,
               num_walkers=args.num_walkers, duration_sec=args.duration_sec)
    assets_dir = REPO_ROOT / "assets" / "scenes" / name
    assets_dir.mkdir(parents=True, exist_ok=True)
    write_text(REPO_ROOT / "configs" / "scenes" / name / "episode.sh", EPISODE_TEMPLATE.format(**fmt), args.overwrite)
    write_text(REPO_ROOT / "configs" / "scenes" / name / "batch" / "smoke_test.sh", SMOKE_TEMPLATE, args.overwrite)
    write_text(REPO_ROOT / "docs" / "scenes" / f"{name}.md", DOC_TEMPLATE.format(**fmt), args.overwrite)
    print("Next step:")
    print(f"  python tools/map_annotator/convert_roi_to_minimal_assets.py --annotated-npz <raw_npz> "
          f"--base-npz <base_npz> --output-dir {assets_dir.relative_to(REPO_ROOT)} --overwrite")


if __name__ == "__main__":
    main()
